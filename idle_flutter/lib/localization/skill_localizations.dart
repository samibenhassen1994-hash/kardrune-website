typedef _SkillText = (String, String, String, String);

extension LocalizedSkillDefinition on SkillDefinition {
  SkillDefinition localized(BuildContext context) =>
      localizedFor(context.krLanguage);

  SkillDefinition localizedFor(KrLanguage language) {
    final text = _skillTexts[language]?[id];
    if (text == null) return this;
    return SkillDefinition(
      id: id,
      name: text.$1,
      rarity: rarity,
      description: text.$2,
      trigger: text.$3,
      limit: text.$4,
      vfx: vfx,
    );
  }
}

