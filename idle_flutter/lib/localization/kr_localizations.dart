import 'package:flutter/widgets.dart';

enum KrLanguage {
  english('en', '🇬🇧', 'English'),
  italian('it', '🇮🇹', 'Italiano'),
  spanish('es', '🇪🇸', 'Español'),
  japanese('ja', '🇯🇵', '日本語'),
  korean('ko', '🇰🇷', '한국어'),
  chinese('zh', '🇨🇳', '简体中文'),
  german('de', '🇩🇪', 'Deutsch');

  const KrLanguage(this.code, this.flag, this.label);
  final String code;
  final String flag;
  final String label;
  Locale get locale => Locale(code);

  static KrLanguage fromCode(String? code) => values.firstWhere(
    (value) => value.code == code?.split(RegExp('[-_]')).first,
    orElse: () => english,
  );
}

class KrLocaleScope extends InheritedWidget {
  const KrLocaleScope({
    super.key,
    required this.language,
    required super.child,
  });

  final KrLanguage language;

  static KrLanguage languageOf(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<KrLocaleScope>()?.language ??
      KrLanguage.english;

  @override
  bool updateShouldNotify(KrLocaleScope oldWidget) =>
      language != oldWidget.language;
}

extension KrTranslationContext on BuildContext {
  KrLanguage get krLanguage => KrLocaleScope.languageOf(this);
  String tr(String english) => KrTranslations.translate(krLanguage, english);
}

