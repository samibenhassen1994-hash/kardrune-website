'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const {decide}=require('../cloud-sync-rules.js');
const old='{"shards":1500}',next='{"shards":1600}',other='{"shards":1700}';
test('matching cloud and local saves safely link without uploading',()=>assert.equal(decide(old,old,1,null),'adopt'));
test('unknown device with different cloud save needs explicit decision',()=>assert.equal(decide(old,other,2,null),'review'));
test('same revision and unchanged local save remains synced',()=>assert.equal(decide(old,other,3,{revision:3,snapshot:old}),'synced'));
test('same revision and local changes may upload with compare-and-swap',()=>assert.equal(decide(next,old,1,{revision:1,snapshot:old}),'upload'));
test('remote advance and clean local allows automatic download',()=>assert.equal(decide(old,other,2,{revision:1,snapshot:old}),'download'));
test('remote and local changes need explicit conflict resolution',()=>assert.equal(decide(next,other,2,{revision:1,snapshot:old}),'review'));
test('remote rollback is never overwritten automatically',()=>assert.equal(decide(old,other,1,{revision:3,snapshot:old}),'review'));
test('no cloud backup must be explicitly initialized',()=>assert.equal(decide(old,null,0,null),'review'));
